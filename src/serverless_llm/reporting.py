"""Aggregate completed suite runs into report-ready tables and figures."""

import json
from collections import defaultdict
from dataclasses import dataclass
from html import escape
from math import sqrt
from pathlib import Path
from statistics import mean, stdev

from serverless_llm.result_writer import ResultWriterError, write_csv, write_json


RUN_FIELDS = (
    "workload_name",
    "policy_name",
    "repetition",
    "execution_order",
    "total_requests",
    "experiment_duration_seconds",
    "mean_end_to_end_ttft_seconds",
    "p95_end_to_end_ttft_seconds",
    "p95_end_to_end_latency_seconds",
    "ttft_slo_violation_rate",
    "cold_start_rate",
    "total_startup_time_seconds",
    "estimated_energy_watt_hours",
    "energy_per_request_watt_hours",
)

METRIC_FIELDS = RUN_FIELDS[5:]


@dataclass(frozen=True)
class ReportPaths:
    """Store paths generated by one report aggregation."""

    runs_csv: Path
    comparison_csv: Path
    report_table_markdown: Path
    report_manifest_json: Path
    figure_paths: tuple[Path, ...]


def _read_json(path: Path) -> dict[str, object]:
    """Read one JSON object and provide a path-aware error."""

    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ResultWriterError(f"Could not read result {path}: {error}") from error
    if not isinstance(value, dict):
        raise ResultWriterError(f"Expected a JSON object in {path}")
    return value


def collect_run_rows(suite_directory: Path) -> list[dict[str, object]]:
    """Read all complete runs and flatten their main report metrics."""

    if not isinstance(suite_directory, Path):
        raise ValueError("suite_directory must be a Path object")

    summary_paths = sorted(suite_directory.glob("*/*/repetition-*/summary.json"))
    if not summary_paths:
        raise ResultWriterError(
            f"No completed summary.json files found under {suite_directory}"
        )

    rows: list[dict[str, object]] = []
    for summary_path in summary_paths:
        run_directory = summary_path.parent
        manifest_path = run_directory / "manifest.json"
        if not manifest_path.exists():
            raise ResultWriterError(
                f"Missing reproducibility manifest: {manifest_path}"
            )

        summary = _read_json(summary_path)
        manifest = _read_json(manifest_path)
        requests = summary["request_summary"]
        startups = summary["startup_summary"]
        gpu = summary["gpu_summary"]
        if not all(isinstance(item, dict) for item in (requests, startups, gpu)):
            raise ResultWriterError(f"Invalid summary structure: {summary_path}")

        total_requests = int(requests["total_requests"])
        energy = float(gpu["estimated_energy_watt_hours"])
        rows.append(
            {
                "workload_name": manifest["workload_name"],
                "policy_name": manifest["policy_name"],
                "repetition": manifest["repetition"],
                "execution_order": manifest["execution_order"],
                "total_requests": total_requests,
                "experiment_duration_seconds": summary[
                    "experiment_duration_seconds"
                ],
                "mean_end_to_end_ttft_seconds": requests[
                    "mean_end_to_end_ttft_seconds"
                ],
                "p95_end_to_end_ttft_seconds": requests[
                    "p95_end_to_end_ttft_seconds"
                ],
                "p95_end_to_end_latency_seconds": requests[
                    "p95_end_to_end_latency_seconds"
                ],
                "ttft_slo_violation_rate": requests[
                    "ttft_slo_violation_rate"
                ],
                "cold_start_rate": startups["cold_start_rate"],
                "total_startup_time_seconds": startups[
                    "total_startup_time_seconds"
                ],
                "estimated_energy_watt_hours": energy,
                "energy_per_request_watt_hours": energy / total_requests,
            }
        )

    return rows


def _statistics(values: list[float]) -> tuple[float, float | None, float | None]:
    """Return mean, sample standard deviation, and normal 95% CI half-width."""

    average = mean(values)
    if len(values) < 2:
        return average, None, None
    deviation = stdev(values)
    return average, deviation, 1.96 * deviation / sqrt(len(values))


def aggregate_run_rows(
    rows: list[dict[str, object]],
) -> list[dict[str, object]]:
    """Aggregate repetitions for each workload and policy."""

    groups: dict[tuple[str, str], list[dict[str, object]]] = defaultdict(list)
    for row in rows:
        groups[(str(row["workload_name"]), str(row["policy_name"]))].append(row)

    aggregated: list[dict[str, object]] = []
    for (workload_name, policy_name), group in sorted(groups.items()):
        output: dict[str, object] = {
            "workload_name": workload_name,
            "policy_name": policy_name,
            "repetitions": len(group),
        }
        for metric in METRIC_FIELDS:
            values = [float(row[metric]) for row in group]
            average, deviation, ci95 = _statistics(values)
            output[f"{metric}_mean"] = average
            output[f"{metric}_stddev"] = deviation
            output[f"{metric}_ci95"] = ci95
        aggregated.append(output)
    return aggregated


def _write_text_exclusive(path: Path, text: str) -> None:
    """Write a new text artifact without overwriting prior evidence."""

    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("x", encoding="utf-8") as output_file:
            output_file.write(text)
    except FileExistsError as error:
        raise ResultWriterError(f"Report artifact already exists: {path}") from error
    except OSError as error:
        raise ResultWriterError(f"Could not write report artifact: {error}") from error


def _format_estimate(row: dict[str, object], metric: str) -> str:
    average = float(row[f"{metric}_mean"])
    ci95 = row[f"{metric}_ci95"]
    return f"{average:.4f}" if ci95 is None else f"{average:.4f} ± {float(ci95):.4f}"


def build_markdown_table(aggregated: list[dict[str, object]]) -> str:
    """Build a compact table suitable for direct report inclusion."""

    lines = [
        "# Serverless LLM policy comparison",
        "",
        "Values are mean ± 95% confidence-interval half-width across repetitions.",
        "",
        "| Workload | Policy | n | P95 E2E TTFT (s) | Cold-start rate | SLO violation rate | Energy/request (Wh) |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for row in aggregated:
        lines.append(
            "| {workload} | {policy} | {n} | {ttft} | {cold} | {slo} | {energy} |".format(
                workload=row["workload_name"],
                policy=row["policy_name"],
                n=row["repetitions"],
                ttft=_format_estimate(row, "p95_end_to_end_ttft_seconds"),
                cold=_format_estimate(row, "cold_start_rate"),
                slo=_format_estimate(row, "ttft_slo_violation_rate"),
                energy=_format_estimate(row, "energy_per_request_watt_hours"),
            )
        )
    return "\n".join(lines) + "\n"


def _build_svg(
    aggregated: list[dict[str, object]],
    metric: str,
    title: str,
) -> str:
    """Build a dependency-free SVG bar chart for one comparison metric."""

    width = 1100
    bar_height = 28
    gap = 14
    left = 300
    top = 70
    height = top + len(aggregated) * (bar_height + gap) + 55
    values = [float(row[f"{metric}_mean"]) for row in aggregated]
    maximum = max(values) if any(values) else 1.0
    colors = {
        "always_on": "#2563eb",
        "naive_serverless": "#dc2626",
        "fixed_keep_warm": "#16a34a",
    }
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="white"/>',
        f'<text x="24" y="36" font-family="sans-serif" font-size="22" font-weight="bold">{escape(title)}</text>',
    ]
    for index, (row, value) in enumerate(zip(aggregated, values)):
        y = top + index * (bar_height + gap)
        label = f'{row["workload_name"]} / {row["policy_name"]}'
        bar_width = (width - left - 120) * value / maximum
        color = colors.get(str(row["policy_name"]), "#64748b")
        parts.extend(
            [
                f'<text x="24" y="{y + 20}" font-family="sans-serif" font-size="14">{escape(label)}</text>',
                f'<rect x="{left}" y="{y}" width="{bar_width:.2f}" height="{bar_height}" fill="{color}"/>',
                f'<text x="{left + bar_width + 8:.2f}" y="{y + 20}" font-family="sans-serif" font-size="14">{value:.4f}</text>',
            ]
        )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def generate_report(suite_directory: Path) -> ReportPaths:
    """Create run-level data, aggregate statistics, tables, and figures."""

    rows = collect_run_rows(suite_directory)
    aggregated = aggregate_run_rows(rows)
    aggregate_directory = suite_directory / "aggregate"
    runs_csv = aggregate_directory / "runs.csv"
    comparison_csv = aggregate_directory / "policy-comparison.csv"
    markdown_path = aggregate_directory / "report-table.md"
    manifest_path = aggregate_directory / "report-manifest.json"

    aggregate_fields = ("workload_name", "policy_name", "repetitions") + tuple(
        f"{metric}_{suffix}"
        for metric in METRIC_FIELDS
        for suffix in ("mean", "stddev", "ci95")
    )
    write_csv(runs_csv, RUN_FIELDS, rows)
    write_csv(comparison_csv, aggregate_fields, aggregated)
    _write_text_exclusive(markdown_path, build_markdown_table(aggregated))

    figures: list[Path] = []
    for metric, title in (
        ("p95_end_to_end_ttft_seconds", "P95 end-to-end TTFT (seconds)"),
        ("cold_start_rate", "Cold-start rate"),
        ("ttft_slo_violation_rate", "TTFT SLO violation rate"),
        ("energy_per_request_watt_hours", "Estimated GPU energy per request (Wh)"),
    ):
        path = aggregate_directory / f"{metric}.svg"
        _write_text_exclusive(path, _build_svg(aggregated, metric, title))
        figures.append(path)

    write_json(
        manifest_path,
        {
            "schema_version": 1,
            "suite_directory": str(suite_directory),
            "run_count": len(rows),
            "group_count": len(aggregated),
            "confidence_interval": (
                "normal approximation: mean ± 1.96 * sample_stddev / sqrt(n)"
            ),
            "source_manifests": [
                str(path.relative_to(suite_directory))
                for path in sorted(suite_directory.glob("*/*/repetition-*/manifest.json"))
            ],
        },
    )

    return ReportPaths(
        runs_csv=runs_csv,
        comparison_csv=comparison_csv,
        report_table_markdown=markdown_path,
        report_manifest_json=manifest_path,
        figure_paths=tuple(figures),
    )
